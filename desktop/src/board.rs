#![expect(
    clippy::same_name_method,
    reason = "generated by the Props derive macro"
)]

use dioxus::prelude::*;
use rightchess::{Color, Fen, Piece, PieceKind};

#[component]
pub fn ChessBoard(fen: Fen) -> Element {
    rsx! {
        div { class: "board",
            for (y, (rank, pieces)) in ('1'..='8').rev().zip(fen.squares()).enumerate() {
                for (x, (file, square)) in ('a'..='h').zip(pieces).enumerate() {
                    div {
                        class: if (x + y) % 2 == 0 { "square light" } else { "square dark" },
                        "data-square": "{file}{rank}",
                        dangerous_inner_html: square.map_or("", svg),
                    }
                }
            }
        }
    }
}

fn svg(piece: Piece) -> &'static str {
    match (piece.color, piece.kind) {
        (Color::White, PieceKind::Pawn) => include_str!("../assets/pieces/wP.svg"),
        (Color::White, PieceKind::Knight) => include_str!("../assets/pieces/wN.svg"),
        (Color::White, PieceKind::Bishop) => include_str!("../assets/pieces/wB.svg"),
        (Color::White, PieceKind::Rook) => include_str!("../assets/pieces/wR.svg"),
        (Color::White, PieceKind::Queen) => include_str!("../assets/pieces/wQ.svg"),
        (Color::White, PieceKind::King) => include_str!("../assets/pieces/wK.svg"),
        (Color::Black, PieceKind::Pawn) => include_str!("../assets/pieces/bP.svg"),
        (Color::Black, PieceKind::Knight) => include_str!("../assets/pieces/bN.svg"),
        (Color::Black, PieceKind::Bishop) => include_str!("../assets/pieces/bB.svg"),
        (Color::Black, PieceKind::Rook) => include_str!("../assets/pieces/bR.svg"),
        (Color::Black, PieceKind::Queen) => include_str!("../assets/pieces/bQ.svg"),
        (Color::Black, PieceKind::King) => include_str!("../assets/pieces/bK.svg"),
    }
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    fn render(fen: &str) -> String {
        let fen: Fen = fen.parse().expect("valid FEN");
        dioxus_ssr::render_element(rsx! { ChessBoard { fen } })
    }

    fn drawn_squares(html: &str) -> Vec<&str> {
        html.split(r#"data-square=""#)
            .skip(1)
            .filter_map(|rest| rest.split('"').next())
            .collect()
    }

    #[test]
    fn draws_rank_8_at_the_top_and_the_a_file_on_the_left() {
        let html = render("4k3/8/8/8/8/8/8/4K3 w - - 0 1");
        let expected: Vec<String> = ('1'..='8')
            .rev()
            .flat_map(|rank| ('a'..='h').map(move |file| format!("{file}{rank}")))
            .collect();
        assert_eq!(drawn_squares(&html), expected);
    }

    #[test]
    fn a1_is_dark_and_h1_is_light() {
        let html = render("4k3/8/8/8/8/8/8/4K3 w - - 0 1");
        for (square, shade) in [
            ("a1", "dark"),
            ("h1", "light"),
            ("a8", "light"),
            ("h8", "dark"),
        ] {
            assert!(
                html.contains(&format!(r#"class="square {shade}" data-square="{square}""#)),
                "{square} should be {shade}: {html}"
            );
        }
    }

    #[test]
    fn pieces_stand_on_their_squares() {
        let html = render(Fen::starting().as_str());
        let piece = |color, kind| svg(Piece { color, kind });
        for (square, color, kind) in [
            ("a8", Color::Black, PieceKind::Rook),
            ("e8", Color::Black, PieceKind::King),
            ("d1", Color::White, PieceKind::Queen),
            ("g1", Color::White, PieceKind::Knight),
            ("c7", Color::Black, PieceKind::Pawn),
            ("f2", Color::White, PieceKind::Pawn),
        ] {
            assert!(
                html.contains(&format!(r#"data-square="{square}">{}"#, piece(color, kind))),
                "{color:?} {kind:?} should be on {square}"
            );
        }
        assert!(
            html.contains(r#"data-square="e4"></div>"#),
            "e4 should be empty: {html}"
        );
    }

    #[test]
    fn every_piece_has_its_own_image() {
        let images: HashSet<_> = [Color::White, Color::Black]
            .into_iter()
            .flat_map(|color| {
                [
                    PieceKind::Pawn,
                    PieceKind::Knight,
                    PieceKind::Bishop,
                    PieceKind::Rook,
                    PieceKind::Queen,
                    PieceKind::King,
                ]
                .map(|kind| svg(Piece { color, kind }))
            })
            .filter(|image| image.starts_with("<svg"))
            .collect();
        assert_eq!(images.len(), 12, "twelve distinct piece images");
    }
}
