use dioxus::prelude::*;
use rightchess::{Color, Fen, Pgn};

use crate::board::ChessBoard;
use crate::components::button::{Button, ButtonVariant};

#[component]
pub fn GameViewer(pgn: Pgn) -> Element {
    let (fens, error) = positions(&pgn);
    let mut index = use_signal(|| 0);
    let last = fens.len().saturating_sub(1);
    let current = index().min(last);
    let mut back = move || index.set(index().min(last).saturating_sub(1));
    let mut forward = move || index.set((index() + 1).min(last));
    let note = error.map(|reason| match fens.len() {
        0 => format!("Can't show this game: {reason}"),
        n => format!("Stopped after position {n}: {reason}"),
    });

    rsx! {
        div {
            class: "viewer",
            tabindex: 0,
            onmounted: move |event| async move { event.set_focus(true).await.unwrap_or_default() },
            onkeydown: move |event| {
                let key = event.key();
                if key == Key::ArrowLeft {
                    back();
                } else if key == Key::ArrowRight {
                    forward();
                }
            },
            if let Some(fen) = fens.get(current) {
                ChessBoard { fen: fen.clone() }
                div { class: "viewer-controls",
                    Button {
                        variant: ButtonVariant::Outline,
                        disabled: current == 0,
                        onclick: move |_| back(),
                        "◀"
                    }
                    span { class: "viewer-label",
                        "Position {current + 1} of {fens.len()} · {side(fen)} to play"
                    }
                    Button {
                        variant: ButtonVariant::Outline,
                        disabled: current == last,
                        onclick: move |_| forward(),
                        "▶"
                    }
                }
            }
            if let Some(note) = note {
                div { class: "viewer-note", "{note}" }
            }
        }
    }
}

/// The positions that could be played, then why the rest couldn't, if a move failed.
fn positions(pgn: &Pgn) -> (Vec<Fen>, Option<String>) {
    let mut results: Vec<_> = pgn.fens().collect();
    let error = results
        .pop_if(|result| result.is_err())
        .and_then(Result::err);
    let fens = results.into_iter().flatten().collect();
    (fens, error.map(|err| format!("{err:#}")))
}

fn side(fen: &Fen) -> &'static str {
    match fen.side_to_move() {
        Color::White => "White",
        Color::Black => "Black",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pgn(text: &str) -> Pgn {
        text.parse().expect("valid PGN")
    }

    fn render(text: &str) -> String {
        let pgn = pgn(text);
        dioxus_ssr::render_element(rsx! { GameViewer { pgn } })
    }

    #[test]
    fn a_game_gives_the_start_then_a_position_per_ply() {
        let (fens, error) = positions(&pgn("1. e4 e5 2. Nf3"));
        assert_eq!(fens.len(), 4, "{fens:?}");
        assert_eq!(fens[0], Fen::starting());
        assert_eq!(
            fens[3].as_str(),
            "rnbqkbnr/pppp1ppp/8/4p3/4P3/5N2/PPPP1PPP/RNBQKB1R b KQkq - 1 2"
        );
        assert_eq!(error, None);
    }

    #[test]
    fn an_unplayable_ply_ends_the_positions_with_its_reason() {
        let (fens, error) = positions(&pgn("1. e4 e5 2. Ke3"));
        assert_eq!(fens.len(), 3, "{fens:?}");
        let error = error.expect("Ke3 can't be played");
        assert!(error.contains("Ke3"), "{error}");
    }

    #[test]
    fn a_fen_tag_sets_the_first_position() {
        let start = "4k3/8/8/8/8/8/8/4K3 w - - 0 1";
        let (fens, error) = positions(&pgn(&format!(
            "[Variant \"From Position\"]\n[FEN \"{start}\"]\n\n1. Kd2"
        )));
        assert_eq!(fens.len(), 2, "{fens:?}");
        assert_eq!(fens[0].as_str(), start);
        assert_eq!(error, None);
    }

    #[test]
    fn a_game_without_moves_has_only_its_start() {
        let (fens, error) = positions(&pgn("[Result \"*\"]\n\n*"));
        assert_eq!(fens, [Fen::starting()]);
        assert_eq!(error, None);
    }

    #[test]
    fn an_unsupported_variant_has_no_positions() {
        let (fens, error) = positions(&pgn(
            "[Variant \"Chess960\"]\n[FEN \"qbrnkrbn/pppppppp/8/8/8/8/PPPPPPPP/QBRNKRBN w KQkq - 0 1\"]",
        ));
        assert_eq!(fens, []);
        let error = error.expect("Chess960 isn't supported");
        assert!(error.contains("Chess960"), "{error}");
    }

    #[test]
    fn opens_on_the_first_position() {
        let html = render("1. e4 e5 2. Nf3");
        assert!(html.contains("Position 1 of 4 · White to play"), "{html}");
        assert!(html.contains(r#"class="board""#), "{html}");
    }

    #[test]
    fn steps_are_disabled_at_the_ends() {
        let count = |html: &str| html.matches("disabled=true").count();
        assert_eq!(count(&render("1. e4")), 1, "only back at the start");
        assert_eq!(count(&render("*")), 2, "both with a single position");
    }

    #[test]
    fn notes_where_a_game_stopped() {
        let html = render("1. e4 e5 2. Ke3");
        assert!(html.contains("Stopped after position 3: "), "{html}");
        assert!(html.contains("Position 1 of 3"), "{html}");
    }

    #[test]
    fn a_game_with_no_positions_shows_only_why() {
        let html = render("[Variant \"Chess960\"]\n\n1. e4");
        assert!(
            html.contains("show this game: unsupported variant"),
            "{html}"
        );
        assert!(!html.contains(r#"class="board""#), "{html}");
        assert!(!html.contains("Position "), "{html}");
    }
}
